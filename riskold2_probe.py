"""(riskold2) 위험 2개 이상 구간 시작일 → 이후 고점 → 그 뒤 저점(시작 뒤 2년 안)이 시작일 지수보다 낮았나(2026-11-25 사용자: 큰 자본이 빠지는 시차)."""
import FinanceDataReader as fdr, pandas as pd
ks = fdr.DataReader("KS11", "1998-01-01")["Close"].dropna()
for d0 in ["1999-01-04","1999-02-24","1999-04-06","1999-06-04","2000-05-03","2001-04-19","2001-11-23","2002-03-20","2006-05-03","2007-06-08","2026-01-29","2026-04-21"]:
    s = ks[d0:]; p0 = s.iloc[0]; w = s.iloc[:500]; pk_d = w.iloc[:250].idxmax(); pk = w[pk_d]
    aft = w[pk_d:]; lo_d = aft.idxmin(); lo = aft[lo_d]
    print(f"{d0}: 시작 {p0:,.0f} → 고점 {pk_d:%Y-%m-%d} {pk/p0*100-100:+.0f}% → 그 뒤 2년 안 저점 {lo_d:%Y-%m-%d} 시작 대비 {lo/p0*100-100:+.0f}% (고점 대비 {lo/pk*100-100:+.0f}%)"
          + ("" if len(s) >= 500 else " · 2년 안 됨"))
